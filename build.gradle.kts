import org.jetbrains.kotlin.gradle.targets.js.yarn.YarnPlugin
import org.jetbrains.kotlin.gradle.targets.js.yarn.YarnRootExtension
import org.jetbrains.kotlin.gradle.targets.wasm.nodejs.WasmNodeJsRootExtension
import org.jetbrains.kotlin.gradle.targets.wasm.nodejs.WasmNodeJsRootPlugin

plugins {
    // this is necessary to avoid the plugins to be loaded multiple times
    // in each subproject's classloader
    alias(libs.plugins.androidApplication) apply false
    alias(libs.plugins.androidMultiplatformLibrary) apply false
    alias(libs.plugins.composeMultiplatform) apply false
    alias(libs.plugins.composeCompiler) apply false
    alias(libs.plugins.kotlinMultiplatform) apply false
    alias(libs.plugins.ksp) apply false
}

rootProject.plugins.withType<YarnPlugin> {
    rootProject.extensions.getByType<YarnRootExtension>().apply {
        // Kotlin/JS toolchain packages are generated by the Kotlin Gradle plugin.
        // Keep known transitive vulnerabilities on patched versions in the shared lockfile.
        // braces remains at 3.0.3 because GHSA-vfj7-8cjw-p6xm has no patched release yet.
        resolution("webpack-dev-server", "5.2.6")
        resolution("webpack", "5.104.1")
        resolution("mocha", "12.0.3")
        resolution("uuid", "11.1.1")
    }
}

rootProject.plugins.withType<WasmNodeJsRootPlugin> {
    rootProject.extensions.getByType<WasmNodeJsRootExtension>().versions.apply {
        // Kotlin/Wasm installs its compiler tooling into a separate npm tree.
        webpack.version = "5.104.1"
        webpackDevServer.version = "5.2.6"
        mocha.version = "12.0.3"
    }
}
